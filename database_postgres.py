"""PostgreSQL schema creation kept separate from SQLite-specific migrations."""

POSTGRES_SCHEMA = (
    """
    CREATE TABLE IF NOT EXISTS users (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL, email TEXT UNIQUE NOT NULL, phone TEXT, cpf TEXT,
        birth_date TEXT, zip_code TEXT, address TEXT, address_number TEXT,
        address_complement TEXT, neighborhood TEXT, city TEXT, state TEXT,
        password_hash TEXT NOT NULL, first_access_required INTEGER NOT NULL DEFAULT 0,
        role TEXT NOT NULL DEFAULT 'customer', created_at TEXT DEFAULT CURRENT_TIMESTAMP,
        active INTEGER NOT NULL DEFAULT 1, session_version INTEGER NOT NULL DEFAULT 0
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS barbers (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER UNIQUE REFERENCES users(id), name TEXT NOT NULL, bio TEXT,
        photo_url TEXT, active INTEGER DEFAULT 1, work_start TEXT DEFAULT '09:00',
        work_end TEXT DEFAULT '18:00', lunch_start TEXT DEFAULT '12:00',
        lunch_end TEXT DEFAULT '13:00', work_days TEXT DEFAULT '[1,2,3,4,5,6]'
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS services (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL, description TEXT, price REAL NOT NULL,
        duration_min INTEGER DEFAULT 30, category TEXT DEFAULT 'Cabelo',
        active INTEGER DEFAULT 1, image_url TEXT
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS products (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL, description TEXT, price REAL NOT NULL,
        stock INTEGER DEFAULT 0, image_url TEXT, category TEXT DEFAULT 'Geral',
        active INTEGER DEFAULT 1, cost_price REAL NOT NULL DEFAULT 0
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS orders (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER REFERENCES users(id), customer_name TEXT NOT NULL,
        customer_phone TEXT, address TEXT, total REAL NOT NULL,
        status TEXT DEFAULT 'pending', payment_method TEXT,
        created_at TEXT DEFAULT CURRENT_TIMESTAMP
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS appointments (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES users(id),
        barber_id INTEGER NOT NULL REFERENCES barbers(id),
        service_id INTEGER NOT NULL REFERENCES services(id),
        appointment_date TEXT NOT NULL, start_time TEXT NOT NULL, end_time TEXT NOT NULL,
        status TEXT DEFAULT 'scheduled', notes TEXT, created_at TEXT DEFAULT CURRENT_TIMESTAMP,
        service_price_cents INTEGER
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS order_items (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        order_id INTEGER NOT NULL REFERENCES orders(id),
        product_id INTEGER NOT NULL REFERENCES products(id),
        product_name TEXT NOT NULL, quantity INTEGER NOT NULL, price REAL NOT NULL
    )
    """,
    "CREATE TABLE IF NOT EXISTS settings (key TEXT PRIMARY KEY, value TEXT)",
    """
    CREATE TABLE IF NOT EXISTS stock_movements (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        product_id INTEGER NOT NULL REFERENCES products(id),
        movement_type TEXT NOT NULL CHECK (movement_type IN ('opening','purchase','sale','adjustment','return')),
        quantity INTEGER NOT NULL CHECK (quantity <> 0),
        unit_cost_cents INTEGER NOT NULL DEFAULT 0 CHECK (unit_cost_cents >= 0),
        note TEXT, order_id INTEGER REFERENCES orders(id),
        created_by INTEGER REFERENCES users(id), created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
    """,
    "CREATE INDEX IF NOT EXISTS idx_stock_movements_product_date ON stock_movements(product_id, created_at DESC)",
    "CREATE INDEX IF NOT EXISTS idx_stock_movements_order ON stock_movements(order_id)",
    """
    CREATE TABLE IF NOT EXISTS portfolio (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        name TEXT NOT NULL, description TEXT, image_url TEXT,
        category TEXT DEFAULT 'Corte', service_id INTEGER REFERENCES services(id),
        barber_id INTEGER REFERENCES barbers(id)
    )
    """,
    "CREATE UNIQUE INDEX IF NOT EXISTS idx_users_cpf_unique ON users(cpf) WHERE cpf IS NOT NULL AND cpf <> ''",
    """
    CREATE TABLE IF NOT EXISTS auth_login_attempts (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        email TEXT NOT NULL, client_ip TEXT NOT NULL, attempted_at TEXT NOT NULL,
        succeeded INTEGER NOT NULL DEFAULT 0
    )
    """,
    "CREATE INDEX IF NOT EXISTS idx_auth_login_attempts_lookup ON auth_login_attempts(email, client_ip, attempted_at, succeeded)",
    """
    CREATE TABLE IF NOT EXISTS password_reset_tokens (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id INTEGER NOT NULL REFERENCES users(id), email TEXT NOT NULL,
        token_hash TEXT NOT NULL UNIQUE, expires_at TEXT NOT NULL,
        created_at TEXT NOT NULL, used_at TEXT
    )
    """,
    "CREATE INDEX IF NOT EXISTS idx_password_reset_email_created ON password_reset_tokens(email, created_at)",
    """
    CREATE TABLE IF NOT EXISTS financial_transactions (
        id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        transaction_type TEXT NOT NULL CHECK (transaction_type IN ('income','expense')),
        category TEXT NOT NULL, description TEXT NOT NULL,
        amount_cents INTEGER NOT NULL CHECK (amount_cents > 0), occurred_on TEXT NOT NULL,
        payment_method TEXT, status TEXT NOT NULL DEFAULT 'paid'
            CHECK (status IN ('pending','paid','cancelled')),
        barber_id INTEGER REFERENCES barbers(id), order_id INTEGER REFERENCES orders(id),
        appointment_id INTEGER REFERENCES appointments(id), created_by INTEGER REFERENCES users(id),
        created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
        reversal_of_id INTEGER REFERENCES financial_transactions(id)
    )
    """,
    "CREATE INDEX IF NOT EXISTS idx_financial_transactions_date_status ON financial_transactions(occurred_on, status, transaction_type)",
    "CREATE UNIQUE INDEX IF NOT EXISTS idx_financial_transactions_reversal_unique ON financial_transactions(reversal_of_id) WHERE reversal_of_id IS NOT NULL",
    "CREATE UNIQUE INDEX IF NOT EXISTS idx_financial_transactions_appointment_unique ON financial_transactions(appointment_id) WHERE appointment_id IS NOT NULL",
    "CREATE UNIQUE INDEX IF NOT EXISTS idx_financial_transactions_order_unique ON financial_transactions(order_id) WHERE order_id IS NOT NULL",
    """
    CREATE TABLE IF NOT EXISTS barber_commission_settings (
        barber_id INTEGER PRIMARY KEY REFERENCES barbers(id),
        commission_percent REAL NOT NULL DEFAULT 0 CHECK (commission_percent >= 0 AND commission_percent <= 100),
        updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
    """,
)


def initialize_postgresql_schema(connection):
    for statement in POSTGRES_SCHEMA:
        connection.execute(statement)
